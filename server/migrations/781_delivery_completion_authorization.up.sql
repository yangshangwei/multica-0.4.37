 actor_agent_id uuid,
 integration_id uuid,
 operation_id uuid,
 mutation_digest text,
 issue_revision_before bigint,
 issue_revision_after bigint,
 status_after text,
 collaboration_operation_id uuid,
 admin_operation_id uuid,
 result_submission_id uuid,
 result_collaboration_revision bigint,
 provider_event_id text,
 provider_event_digest text,
 revoker_user_id uuid,
 revocation_request_key uuid,
 revocation_reason text,
 revocation_digest text,
 CONSTRAINT delivery_completion_terminal_shape CHECK ((kind='consumed' AND operation_id IS NOT NULL AND mutation_digest IS NOT NULL AND mutation_digest ~ '^[0-9a-f]{64}$' AND issue_revision_before IS NOT NULL AND issue_revision_before>=0 AND issue_revision_after IS NOT NULL AND issue_revision_after>=issue_revision_before AND status_after IS NOT NULL AND revoker_user_id IS NULL AND revocation_request_key IS NULL AND revocation_reason IS NULL AND revocation_digest IS NULL) OR (kind='revoked' AND actor_kind='human' AND actor_user_id IS NOT NULL AND revoker_user_id IS NOT NULL AND revoker_user_id=actor_user_id AND revocation_request_key IS NOT NULL AND revocation_reason IS NOT NULL AND char_length(btrim(revocation_reason)) BETWEEN 1 AND 1000 AND revocation_digest IS NOT NULL AND revocation_digest ~ '^[0-9a-f]{64}$' AND operation_id IS NULL AND mutation_digest IS NULL AND issue_revision_before IS NULL AND issue_revision_after IS NULL AND status_after IS NULL AND collaboration_operation_id IS NULL AND admin_operation_id IS NULL AND result_submission_id IS NULL AND result_collaboration_revision IS NULL AND provider_event_id IS NULL AND provider_event_digest IS NULL)),
 CHECK ((actor_kind IN ('human','admin') AND actor_user_id IS NOT NULL AND actor_agent_id IS NULL AND integration_id IS NULL) OR (actor_kind='task' AND actor_user_id IS NOT NULL AND actor_agent_id IS NOT NULL AND integration_id IS NULL) OR (actor_kind IN ('github','vcs') AND actor_user_id IS NULL AND actor_agent_id IS NULL AND integration_id IS NOT NULL)),
 CHECK (authorization_id IS NULL OR authorization_id<>'00000000-0000-0000-0000-000000000000'::uuid),
 CHECK (actor_user_id IS NULL OR actor_user_id<>'00000000-0000-0000-0000-000000000000'::uuid),
 CHECK (actor_agent_id IS NULL OR actor_agent_id<>'00000000-0000-0000-0000-000000000000'::uuid),
 CHECK (integration_id IS NULL OR integration_id<>'00000000-0000-0000-0000-000000000000'::uuid),
 CHECK (operation_id IS NULL OR operation_id<>'00000000-0000-0000-0000-000000000000'::uuid),
 CHECK (collaboration_operation_id IS NULL OR collaboration_operation_id<>'00000000-0000-0000-0000-000000000000'::uuid),
 CHECK (admin_operation_id IS NULL OR admin_operation_id<>'00000000-0000-0000-0000-000000000000'::uuid),
 CHECK (result_submission_id IS NULL OR result_submission_id<>'00000000-0000-0000-0000-000000000000'::uuid),
