-- Retain frozen operation facts when live workspaces/principals are removed.
-- Identity indexes are installed by separate concurrent migrations.
CREATE TABLE agent_artifact_execution (
    execution_id uuid NOT NULL,
    approval_id uuid NOT NULL,
    workspace_id uuid NOT NULL,
    initiator_kind text NOT NULL CHECK (initiator_kind IN ('human','agent')),
    initiator_id uuid NOT NULL,
    originator_user_id uuid NOT NULL,
    agent_id uuid NOT NULL,
    task_id uuid NOT NULL,
    runtime_id uuid NOT NULL,
    task_generation bigint NOT NULL CHECK (task_generation >= 0),
    resource_kind text NOT NULL CHECK (resource_kind = 'issue'),
    resource_id uuid NOT NULL,
    action text NOT NULL CHECK (action = 'package_release_candidate'),
    idempotency_key uuid NOT NULL,
    request_digest text NOT NULL CHECK (request_digest ~ '^[0-9a-f]{64}$'),
    canonical_spec bytea NOT NULL CHECK (octet_length(canonical_spec) BETWEEN 1 AND 24576),
    spec_digest text NOT NULL CHECK (spec_digest ~ '^[0-9a-f]{64}$'),
    source_revision text NOT NULL CHECK (source_revision ~ '^([0-9a-f]{40}|[0-9a-f]{64})$'),
    staging_id text NOT NULL CHECK (length(staging_id) BETWEEN 1 AND 96),
    staging_manifest_digest text NOT NULL CHECK (staging_manifest_digest ~ '^[0-9a-f]{64}$'),
    input_manifest_digest text NOT NULL CHECK (input_manifest_digest ~ '^[0-9a-f]{64}$'),
    invocation_digest text NOT NULL CHECK (invocation_digest ~ '^[0-9a-f]{64}$'),
    policy_version text NOT NULL CHECK (policy_version = 'artifact-tar-v1'),
    target_environment text NOT NULL CHECK (target_environment = 'local-synthetic'),
    root_config_identity text NOT NULL CHECK (length(root_config_identity) BETWEEN 1 AND 256),
    created_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    claimed_kind text CHECK (claimed_kind IN ('human','agent')),
    claimed_by uuid,
    claim_nonce uuid,
    claimed_at timestamptz,
    started_at timestamptz,
    finished_at timestamptz,
    result_status text CHECK (result_status IN ('unknown','failed','succeeded')),
    result_code text NOT NULL DEFAULT '' CHECK (length(result_code) <= 96),
    receipt_json jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(receipt_json) = 'object' AND octet_length(receipt_json::text) <= 4096),
    receipt_digest text NOT NULL DEFAULT '' CHECK (receipt_digest = '' OR receipt_digest ~ '^[0-9a-f]{64}$'),
    output_artifact_id uuid,
    output_artifact_digest text NOT NULL DEFAULT '' CHECK (output_artifact_digest = '' OR output_artifact_digest ~ '^[0-9a-f]{64}$'),
    output_size bigint CHECK (output_size >= 0),
    CHECK (expires_at = created_at + interval '15 minutes'),
    CHECK ((claimed_at IS NULL AND claimed_kind IS NULL AND claimed_by IS NULL AND claim_nonce IS NULL AND started_at IS NULL AND finished_at IS NULL AND result_status IS NULL) OR (claimed_at IS NOT NULL AND claimed_kind IS NOT NULL AND claimed_by IS NOT NULL AND claim_nonce IS NOT NULL AND started_at IS NOT NULL AND started_at = claimed_at AND result_status IS NOT NULL)),
    CHECK (result_status IS NULL OR result_status = 'unknown' OR (finished_at IS NOT NULL AND receipt_digest <> '' AND result_code <> '')),
    CHECK (finished_at IS NULL OR (finished_at >= claimed_at AND receipt_digest <> '' AND result_code <> '')),
    CHECK ((result_status IS NOT DISTINCT FROM 'succeeded' AND output_artifact_id IS NOT NULL AND output_artifact_id = execution_id AND output_artifact_digest <> '' AND output_size IS NOT NULL) OR (result_status IS DISTINCT FROM 'succeeded' AND output_artifact_id IS NULL AND output_artifact_digest = '' AND output_size IS NULL))
);
