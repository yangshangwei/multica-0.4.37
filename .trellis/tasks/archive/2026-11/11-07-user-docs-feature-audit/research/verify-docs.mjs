import { mkdtempSync, readdirSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const root = process.cwd();
const { generateDocsBundle } = await import(pathToFileURL(resolve(root, 'scripts/generate-docs-bundle.mjs')));
const bundle = resolve(root, 'server/internal/docs/content');
const temporary = mkdtempSync(resolve(tmpdir(), 'multica-docs-audit-'));
const failures = [];
const files = (directory, prefix = '') => readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
  const name = prefix + entry.name;
  return entry.isDirectory() ? files(resolve(directory, entry.name), name + '/') : [name];
}).sort();
try {
  const generated = generateDocsBundle({ outputRoot: temporary });
  const expectedFiles = files(temporary);
  const actualFiles = files(bundle);
  if (JSON.stringify(expectedFiles) !== JSON.stringify(actualFiles)) failures.push('Generated file inventory differs');
  for (const file of expectedFiles) {
    if (!actualFiles.includes(file) || !readFileSync(resolve(temporary, file)).equals(readFileSync(resolve(bundle, file)))) failures.push(`Generated bytes differ: ${file}`);
  }
  const manifest = JSON.parse(readFileSync(resolve(bundle, 'manifest.json'), 'utf8'));
  const published = new Set(manifest.groups.flatMap(group => group.items.map(item => item.slug)));
  const pages = new Map(files(resolve(bundle, 'pages')).map(file => {
    const page = JSON.parse(readFileSync(resolve(bundle, 'pages', file), 'utf8'));
    return [page.slug, page];
  }));
  let links = 0;
  let images = 0;
  for (const [slug, page] of pages) {
    if (!published.has(slug)) failures.push(`${slug}: missing navigation entry`);
    const body = page.body.replace(/^(`{3,}|~{3,})[^\n]*\n[\s\S]*?^\1\s*$/gm, '');
    for (const match of body.matchAll(/(!?)\[[^\]]*\]\(([^\s)]+)(?:\s+"[^"]*")?\)/g)) {
      const href = match[2];
      if (/^(?:[a-z][a-z\d+.-]*:|\/\/)/i.test(href)) continue;
      const url = new URL(href, `https://docs.invalid/${slug}`);
      const pathname = decodeURIComponent(url.pathname).replace(/^\//, '');
      if (match[1]) {
        images++;
        if (!manifest.assets.includes(pathname)) failures.push(`${slug}: missing image ${href}`);
        continue;
      }
      links++;
      const targetSlug = pathname === '' ? 'index' : pathname;
      const target = pages.get(targetSlug);
      if (!target || !published.has(targetSlug)) failures.push(`${slug}: missing page ${href}`);
      else if (url.hash && !target.toc.some(heading => heading.id === decodeURIComponent(url.hash.slice(1)))) failures.push(`${slug}: missing anchor ${href}`);
    }
  }
  console.log(JSON.stringify({ ...generated, comparedFiles: expectedFiles.length, internalLinks: links, images, failures }, null, 2));
  if (failures.length) process.exitCode = 1;
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
