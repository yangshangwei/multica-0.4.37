export function resolveAvatarIcon(value?: string | null): AvatarIconName | null {
  const icon = parseAvatarIcon(value);
  if (icon) return icon;
  const emoji = parseAvatarEmoji(value);
  if (!emoji) return null;
  const normalized = emoji.replace(/\uFE0F/g, "");
  return Object.hasOwn(LEGACY_EMOJI_ICONS, normalized) ? LEGACY_EMOJI_ICONS[normalized]! : "bot";
}

