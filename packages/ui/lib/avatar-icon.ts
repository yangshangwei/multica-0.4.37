export type AvatarIconName = keyof typeof AVATAR_ICON_COMPONENTS;

const AVATAR_ICON_PREFIX = "icon:";

export function parseAvatarIcon(value?: string | null): AvatarIconName | null {
  if (!value?.startsWith(AVATAR_ICON_PREFIX)) return null;
  const name = value.slice(AVATAR_ICON_PREFIX.length).trim();
  return Object.hasOwn(AVATAR_ICON_COMPONENTS, name) ? name as AvatarIconName : null;
}

export function formatAvatarIcon(name: AvatarIconName): string {
  return AVATAR_ICON_PREFIX + name;
}

