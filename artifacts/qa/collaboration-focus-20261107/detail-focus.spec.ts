import { test, expect } from '@playwright/test';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
import { openDesktop, nativeScreenshot } from '../../../e2e/fixtures/collaboration-native';
const out = resolve('artifacts/qa/collaboration-focus-20261107');
const token = JSON.parse(readFileSync('/Users/artisan/.multica/profiles/desktop-localhost-18572/config.json','utf8')).token;
const issue = JSON.parse(readFileSync(resolve('artifacts/qa/collaboration-20261106/ui-created.json'),'utf8'));
test('Current-source native detail: focused actions, stable geometry, keyboard and narrow viewport', async () => {
  mkdirSync(out,{recursive:true});
  const native = await openDesktop(resolve(out,'native-profile'),{token,deepLink:`multica://account?view=participating&issue=${issue.id}`});
  const {page,app}=native;
  const checks: string[]=[];
  try {
    await native.start();
    await expect(page.getByRole('heading',{name:issue.title,exact:true})).toBeVisible({timeout:45000});
    await page.evaluate(()=>localStorage.setItem('multica-locale','zh-Hans'));
    await page.reload();
    const title=page.getByRole('heading',{name:issue.title,exact:true});
    await expect(title).toBeVisible();
    const win=await app.browserWindow(page); await win.evaluate(w=>w.setContentSize(1380,960));
    const settle=async()=>page.evaluate(async()=>{await document.fonts.ready;await Promise.all(document.getAnimations().filter(a=>a.effect?.getComputedTiming().iterations!==Infinity).map(a=>a.finished.catch(()=>{})));await new Promise<void>(r=>requestAnimationFrame(()=>requestAnimationFrame(()=>r())));});
    await settle();
    await nativeScreenshot(app,page,resolve(out,'01-detail-wide.png'));
    const metrics=()=>page.locator('[data-tab-scroll-root="account-detail"]').evaluate(el=>({height:el.scrollHeight,top:el.scrollTop,descriptionY:document.getElementById('description')!.getBoundingClientRect().y}));
    const opener=page.getByRole('button',{name:'记录结果并完成',exact:true});
    await opener.scrollIntoViewIfNeeded();await settle();const before=await metrics();
    await opener.click();
    const dialog=page.getByRole('dialog',{name:'记录结果并完成',exact:true});
    await expect(dialog).toBeVisible();
    await expect(page.getByRole('dialog')).toHaveCount(1);
    await expect(dialog.getByRole('heading',{name:'记录结果并完成',exact:true})).toBeFocused();
    expect(await metrics()).toEqual(before);
    checks.push('Opening workflow dialog preserves underlying detail height/scroll/requirements position');
    await dialog.getByLabel('结果',{exact:true}).fill('弹框验证草稿，不提交');
    await dialog.getByLabel('依据',{exact:true}).fill('检查关闭后草稿保留');
    await settle();await nativeScreenshot(app,page,resolve(out,'02-result-dialog-wide.png'));
    await page.keyboard.press('Escape');await expect(dialog).toHaveCount(0);await expect(opener).toBeFocused();
    await opener.click();await expect(dialog.getByLabel('结果',{exact:true})).toHaveValue('弹框验证草稿，不提交');
    checks.push('Escape restores opener focus; result and basis survive dismissal');
    await dialog.getByLabel('结果',{exact:true}).fill('');await dialog.getByLabel('依据',{exact:true}).fill('');
    await page.keyboard.press('Escape');
    const more=page.getByRole('button',{name:'更多操作',exact:true});await more.click();
    await page.getByRole('menuitem',{name:'编辑任务',exact:true}).click();
    const edit=page.getByRole('dialog',{name:'编辑任务',exact:true});await expect(edit).toBeVisible();await page.keyboard.press('Escape');await expect(more).toBeFocused();
    checks.push('More menu opens one action dialog and returns focus to More');
    const participants=page.getByRole('button',{name:'参与者',exact:true});await expect(participants).toHaveAttribute('aria-expanded','false');
    await participants.click();await expect(page.getByLabel('当前权限',{exact:true})).toBeVisible();await participants.click();
    const composer=page.getByRole('form',{name:'评论',exact:true});await composer.scrollIntoViewIfNeeded();
    const mentions=composer.getByRole('button',{name:'提及',exact:true});await expect(mentions).toHaveAttribute('aria-expanded','false');await mentions.click();await expect(composer.getByRole('button',{name:'@all · 全体参与者',exact:true})).toBeVisible();await mentions.click();
    await settle();await nativeScreenshot(app,page,resolve(out,'03-discussion-tools.png'));
    checks.push('Permissions and mention tools open intentionally');
    await win.evaluate(w=>w.setContentSize(760,960));await title.scrollIntoViewIfNeeded();await opener.click();await expect(dialog).toBeVisible();await settle();
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
    expect(await dialog.evaluate(el=>el.scrollWidth<=el.clientWidth+1)).toBe(true);
    await nativeScreenshot(app,page,resolve(out,'04-result-dialog-narrow.png'));
    for(let i=0;i<12;i++){await page.keyboard.press('Tab');await expect.poll(()=>dialog.evaluate(el=>({inside:el.contains(document.activeElement),active:document.activeElement?.tagName}))).toMatchObject({inside:true});}
    await page.keyboard.press('Escape');
    checks.push('Narrow native window has no horizontal overflow and Tab remains in dialog');
    await opener.click();
    await page.evaluate(()=>document.documentElement.style.fontSize='24px');await settle();
    expect(await dialog.evaluate(el=>el.scrollWidth<=el.clientWidth+1)).toBe(true);
    await dialog.locator('form').getByRole('button',{name:'关闭',exact:true}).click();
    checks.push('150% root text size keeps dialog content within width and Close reachable');
    expect(native.errors).toEqual([]);
    writeFileSync(resolve(out,'checks.json'),JSON.stringify({checks,errors:native.errors,api:'http://localhost:18572',renderer:'http://localhost:5666',mutations:'None; local draft fields restored empty'},null,2));
  } finally {await app.close();}
});
